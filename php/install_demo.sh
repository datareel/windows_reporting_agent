#!/bin/bash
# install_demo.sh
# Install a read-only live demo of the fleet status pages with a sample
# fleet of made up computers (tools/gen_sample_fleet.py).
#
# Usage: install_demo.sh [--apply] [--count N] [--seed N] WEB_DIR
#
#   WEB_DIR   Web directory for the demo, for example
#             /var/www/html/windows_reporting_agent/demo
#   --apply   Make the changes. Without it the script only shows what it
#             would do (dry run).
#   --count   Number of sample computers (default 48)
#   --seed    Sample fleet seed (default 2026)
#
# The demo has no register, upload or admin pages and needs no login: it
# only shows sample data. The sample reports and settings go in
# WEB_DIR/data, which gets a "Require all denied" .htaccess. Report ages
# are measured from the time the fleet was generated, so the demo looks
# the same until you run the script again. Run it again to refresh the
# fleet; it replaces the sample reports.

APPLY=0
COUNT=48
SEED=2026
while [ $# -gt 0 ]; do
    case "$1" in
	--apply) APPLY=1; shift ;;
	--count) COUNT="$2"; shift 2 ;;
	--seed) SEED="$2"; shift 2 ;;
	-h|--help) sed -n '2,21p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
	-*) echo "Unknown option $1"; exit 1 ;;
	*) break ;;
    esac
done

if [ $# -ne 1 ]; then
    echo "Usage: $0 [--apply] [--count N] [--seed N] WEB_DIR"
    exit 1
fi

WEB_DIR="${1%/}"
SRC_DIR="$(cd "$(dirname "$0")" && pwd)"
GEN="${SRC_DIR}/../tools/gen_sample_fleet.py"
PAGES="status.php report.php wra_lib.php wra_page.php"

case "$WEB_DIR" in /*) ;; *) echo "WEB_DIR must be an absolute path"; exit 1 ;; esac
if [ ! -f "${GEN}" ]; then
    echo "ERROR - ${GEN} not found"
    exit 1
fi

if [ ${APPLY} -eq 0 ]; then
    echo "DRY RUN - nothing will be changed. Run again with --apply to install."
fi

run() {
    echo "+ $*"
    if [ ${APPLY} -eq 1 ]; then
	"$@" || { echo "ERROR - command failed"; exit 1; }
    fi
}

write_file() {
    local dest="$1"
    if [ ${APPLY} -eq 1 ]; then
	cat > "${dest}" || { echo "ERROR - could not write ${dest}"; exit 1; }
	echo "Wrote ${dest}"
    else
	echo "Would write ${dest}:"
	sed 's/^/    /'
    fi
}

run mkdir -p "${WEB_DIR}/data"
for f in ${PAGES}; do
    run cp -p "${SRC_DIR}/${f}" "${WEB_DIR}/${f}"
done

write_file "${WEB_DIR}/index.php" <<'EOF'
<?php
// Generated by install_demo.sh
header('Location: status.php');
exit;
?>
EOF

write_file "${WEB_DIR}/.htaccess" <<'EOF'
# Generated by install_demo.sh: read-only demo with sample data
SetEnv WRA_SERVER_INI data/server.ini

<FilesMatch "^wra_(lib|page)\.php$">
    Require all denied
</FilesMatch>
EOF

write_file "${WEB_DIR}/data/.htaccess" <<'EOF'
# Generated by install_demo.sh: sample reports and settings
Require all denied
EOF

write_file "${WEB_DIR}/data/server.ini" <<'EOF'
; Generated by install_demo.sh: settings for the read-only demo
[paths]
reports_dir = reports
data_dir = .

[status]
late_hours = 24
missing_days = 15
patch_max_age_days = 45
required_apps = "Microsoft 365 Apps*, Zoom Workplace*, Google Chrome"
required_apps_skip_hosts = "srv-*"
unwanted_apps = "uTorrent*, TeamViewer 1[0-4]*, CCleaner*, WinRAR 5*"
; No login: sample data only
public = 1
; Measure ages from the time the sample fleet was generated
reference_time = fleet
EOF

run rm -rf "${WEB_DIR}/data/reports"
run python3 -I "${GEN}" --out "${WEB_DIR}/data/reports" --count "${COUNT}" --seed "${SEED}"

echo ""
echo "Open <url of ${WEB_DIR}>/status.php. Check that <url>/data/server.ini is refused (403)."
exit 0
